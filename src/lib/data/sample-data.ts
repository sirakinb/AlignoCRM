export function getContactById(id: string): Contact | undefined {
  return sampleContacts.find((c) => c.id === id);
}

export function getOwnerById(id: string) {
  return sampleOwners.find((o) => o.id === id);
}

export function getStagesForPipeline(pipelineId: string): Stage[] {
  return sampleStages
    .filter((s) => s.pipeline_id === pipelineId)
    .sort((a, b) => a.position - b.position);
}

export function getDealsForStage(stageId: string): Deal[] {
  return sampleDeals.filter((d) => d.stage_id === stageId);
}
